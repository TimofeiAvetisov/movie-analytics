import csv
import io
import logging
import math
import os
import threading
import time
from contextlib import asynccontextmanager
from datetime import date, datetime, timedelta, timezone

import boto3
import clickhouse_connect
import psycopg
from apscheduler.schedulers.background import BackgroundScheduler
from fastapi import FastAPI, HTTPException, Query

from movie_pipeline import settings

logging.basicConfig(level=logging.INFO)
log = logging.getLogger(__name__)
cycle_lock = threading.Lock()


def clickhouse_client():
    return clickhouse_connect.get_client(host=settings.CLICKHOUSE_HOST,
                                         username=settings.CLICKHOUSE_USER,
                                         password=settings.CLICKHOUSE_PASSWORD,
                                         database="analytics")


def aggregate_day(day: date):
    """Read raw ClickHouse events, materialize daily/cohort values, upsert PostgreSQL."""
    start = time.monotonic()
    log.info("Aggregation started date=%s", day)
    ch = clickhouse_client()
    literal = day.isoformat()  # date is parsed by FastAPI or generated by datetime.date
    row = ch.query(f"""
        SELECT count() AS events, uniqExact(user_id) AS dau,
               avgIf(progress_seconds, event_type = 'VIEW_FINISHED') AS avg_watch,
               countIf(event_type = 'VIEW_STARTED') AS starts,
               countIf(event_type = 'VIEW_FINISHED') AS finishes
        FROM raw_events WHERE toDate(timestamp) = toDate('{literal}')
    """).result_rows[0]
    events, dau, avg_watch, starts, finishes = row
    if avg_watch is None or not math.isfinite(avg_watch):
        avg_watch = 0.0
    metrics = [
        (day, "dau", "", float(dau)),
        (day, "avg_watch_seconds", "", float(avg_watch)),
        (day, "view_conversion", "", float(finishes / starts) if starts else 0.0),
    ]
    movies = ch.query(f"""
        SELECT movie_id, countIf(event_type = 'VIEW_STARTED') AS views
        FROM raw_events WHERE toDate(timestamp) = toDate('{literal}')
        GROUP BY movie_id HAVING views > 0
        ORDER BY views DESC, movie_id
    """).result_rows
    metrics.extend((day, "movie_views", movie_id, float(views)) for movie_id, views in movies)

    first_views = """
        SELECT user_id, min(toDate(timestamp)) AS cohort_date
        FROM raw_events WHERE event_type = 'VIEW_STARTED'
        GROUP BY user_id
    """
    cohort_size = ch.query(f"""
        SELECT uniqExact(user_id) FROM ({first_views})
        WHERE cohort_date = toDate('{literal}')
    """).result_rows[0][0]
    returned = dict(ch.query(f"""
        SELECT dateDiff('day', first.cohort_date, toDate(e.timestamp)) AS life_day,
               uniqExact(e.user_id) AS users
        FROM raw_events AS e
        INNER JOIN ({first_views}) AS first ON e.user_id = first.user_id
        WHERE first.cohort_date = toDate('{literal}')
          AND e.event_type = 'VIEW_STARTED'
          AND toDate(e.timestamp) BETWEEN toDate('{literal}') AND addDays(toDate('{literal}'), 7)
        GROUP BY life_day
    """).result_rows)
    now = datetime.now(timezone.utc)
    cohort = [(day, n, cohort_size, returned.get(n, 0),
               100.0 * returned.get(n, 0) / cohort_size if cohort_size else 0.0, now)
              for n in range(8)]
    metrics.extend([
        (day, "retention_d1", "", cohort[1][4]),
        (day, "retention_d7", "", cohort[7][4]),
    ])

    ch.insert("daily_metrics", [(*metric, now) for metric in metrics],
              column_names=["date", "metric_name", "dimension", "value", "computed_at"])
    ch.insert("cohort_retention", cohort,
              column_names=["cohort_date", "day_number", "cohort_size", "returned_users",
                            "retention_percent", "computed_at"])

    for attempt in range(3):
        try:
            with psycopg.connect(settings.POSTGRES_DSN) as conn:
                with conn.cursor() as cur:
                    cur.executemany("""
                        INSERT INTO daily_metrics (date, metric_name, dimension, value, computed_at)
                        VALUES (%s, %s, %s, %s, %s)
                        ON CONFLICT (date, metric_name, dimension)
                        DO UPDATE SET value = EXCLUDED.value, computed_at = EXCLUDED.computed_at
                    """, [(*metric, now) for metric in metrics])
            break
        except Exception:
            log.exception("PostgreSQL write failed date=%s attempt=%s", day, attempt + 1)
            if attempt == 2:
                raise
            time.sleep(2 ** attempt)
    log.info("Aggregation completed date=%s records=%s metrics=%s duration_seconds=%.3f",
             day, events, len(metrics), time.monotonic() - start)
    return {"date": literal, "records": events, "metrics": len(metrics)}


def export_day(day: date):
    """Overwrite the date-partitioned CSV only after reading all PostgreSQL metrics."""
    with psycopg.connect(settings.POSTGRES_DSN) as conn:
        rows = conn.execute("""
            SELECT date, metric_name, dimension, value, computed_at
            FROM daily_metrics WHERE date = %s ORDER BY metric_name, dimension
        """, (day,)).fetchall()
    if not rows:
        raise ValueError(f"No metrics found for {day}")
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["date", "metric_name", "dimension", "value", "computed_at"])
    writer.writerows(rows)
    key = f"daily/{day.isoformat()}/aggregates.csv"
    boto3.client("s3", endpoint_url=settings.S3_ENDPOINT).put_object(
        Bucket=settings.BUCKET, Key=key, Body=output.getvalue().encode(), ContentType="text/csv")
    log.info("Exported date=%s rows=%s key=%s", day, len(rows), key)
    return {"date": day.isoformat(), "rows": len(rows), "key": key}


def scheduled_cycle():
    if not cycle_lock.acquire(blocking=False):
        log.info("Aggregation cycle already running")
        return
    start = time.monotonic()
    processed = 0
    log.info("Aggregation cycle started")
    try:
        today = datetime.now(timezone.utc).date()
        for offset in range(8):
            processed += aggregate_day(today - timedelta(days=offset))["records"]
        export_day(today - timedelta(days=1))
        log.info("Aggregation cycle completed records=%s duration_seconds=%.3f",
                 processed, time.monotonic() - start)
    except Exception:
        log.exception("Aggregation cycle failed records=%s duration_seconds=%.3f; will retry next run",
                      processed, time.monotonic() - start)
    finally:
        cycle_lock.release()


@asynccontextmanager
async def lifespan(_app: FastAPI):
    scheduler = BackgroundScheduler(timezone="UTC")
    scheduler.add_job(scheduled_cycle, "interval",
                      minutes=float(os.getenv("AGGREGATION_INTERVAL_MINUTES", "5")),
                      max_instances=1, next_run_time=datetime.now(timezone.utc))
    scheduler.start()
    yield
    scheduler.shutdown(wait=False)


app = FastAPI(title="Movie analytics aggregation", lifespan=lifespan)


@app.get("/health")
def health():
    return {"status": "ok"}


@app.post("/recalculate")
def recalculate(day: date = Query(alias="date")):
    if not cycle_lock.acquire(blocking=False):
        raise HTTPException(status_code=409, detail="Aggregation cycle is running")
    try:
        return aggregate_day(day)
    except Exception as exc:
        log.exception("Manual recalculation failed date=%s", day)
        raise HTTPException(status_code=503, detail="Recalculation failed") from exc
    finally:
        cycle_lock.release()


@app.post("/export")
def export(day: date = Query(alias="date")):
    try:
        return export_day(day)
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except Exception as exc:
        log.exception("Manual export failed date=%s", day)
        raise HTTPException(status_code=503, detail="Export failed") from exc
